func TestValidateFailsOnInvalidJSON(t *testing.T) {
	d := mmluDataset(t)
	rows := mmluRows()
	// Three lines so the count check passes, then row 1 fails JSON decoding.
	var sb strings.Builder
	enc := json.NewEncoder(&sb)
	for i, r := range rows {
		if i == 1 {
			sb.WriteString("not json\n")
			continue
		}
		_ = enc.Encode(map[string]any{"index": i, "data": r})
	}
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "mmlu-short.jsonl"), []byte(sb.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	err := NewValidator().Validate(d, dir)
	if err == nil {
		t.Fatal("expected error for invalid JSONL")
	}
	if !strings.Contains(err.Error(), "invalid JSON") {
		t.Errorf("unexpected error: %v", err)
	}
}

func TestRowStringIncludesChoiceValues(t *testing.T) {
	r := extracted{Index: 0, Data: mmluRows()[0]}
	got := rowString(r)
	if !strings.Contains(got, "cyclic subgroup") {
		t.Errorf("rowString missing question: %q", got)
	}
	if !strings.Contains(got, "Laniakea") == strings.Contains(got, "Virgo") {
		t.Errorf("rowString should include choice values: %q", got)
	}
}
