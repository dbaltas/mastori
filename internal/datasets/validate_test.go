package datasets

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const mmluManifest = `
datasets:
  mmlu-short:
    source: cais/mmlu
    config: all
    split: test
    extract: mmlu
    selection:
      start: 0
      count: 3
    validate:
      min_rows: 3
      required_fields: [subject, question, choices, answer]
      spot_checks:
        - index: 0
          contains: "cyclic subgroup"
        - index: 2
          contains: "factor group"
`

func cacheFixture(t *testing.T, rows []map[string]any) string {
	t.Helper()
	dir := t.TempDir()
	f, err := os.Create(filepath.Join(dir, "mmlu-short.jsonl"))
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	enc := json.NewEncoder(f)
	for i, r := range rows {
		if err := enc.Encode(map[string]any{"index": i, "data": r}); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func mmluRows() []map[string]any {
	return []map[string]any{
		{"subject": "abstract_algebra", "question": "The cyclic subgroup of Z_24 generated by 18 has order", "choices": []string{"4", "8"}, "answer": 0},
		{"subject": "astronomy", "question": "What is the name of this supercluster?", "choices": []string{"Virgo", "Laniakea"}, "answer": 1},
		{"subject": "abstract_algebra", "question": "Find the order of the factor group Z_6/<3>.", "choices": []string{"2", "4"}, "answer": 0},
	}
}

func mmluDataset(t *testing.T) Dataset {
	t.Helper()
	m, err := LoadManifest(writeManifest(t, mmluManifest))
	if err != nil {
		t.Fatal(err)
	}
	d, err := m.Get("mmlu-short")
	if err != nil {
		t.Fatal(err)
	}
	return d
}

func TestValidatePasses(t *testing.T) {
	d := mmluDataset(t)
	dir := cacheFixture(t, mmluRows())
	v := NewValidator()
	if err := v.Validate(d, dir); err != nil {
		t.Fatalf("Validate: %v", err)
	}
}

func TestValidateFailsOnMissingCache(t *testing.T) {
	d := mmluDataset(t)
	v := NewValidator()
	err := v.Validate(d, t.TempDir())
	if err == nil {
		t.Fatal("expected error for missing cache file")
	}
	if !strings.Contains(err.Error(), "cache file missing") {
		t.Errorf("unexpected error: %v", err)
	}
}

func TestValidateFailsOnShortCache(t *testing.T) {
	d := mmluDataset(t)
	rows := mmluRows()
	dir := cacheFixture(t, rows[:2])
	err := NewValidator().Validate(d, dir)
	if err == nil {
		t.Fatal("expected error for too few rows")
	}
	if !strings.Contains(err.Error(), "only 2 rows") {
		t.Errorf("unexpected error: %v", err)
	}
}

func TestValidateFailsOnCountMismatch(t *testing.T) {
	d := mmluDataset(t)
	rows := mmluRows()
	rows = append(rows, map[string]any{"subject": "x", "question": "extra", "choices": []string{"a"}, "answer": 0})
	dir := cacheFixture(t, rows)
	err := NewValidator().Validate(d, dir)
	if err == nil {
		t.Fatal("expected error for row count mismatch")
	}
	if !strings.Contains(err.Error(), "expected exactly 3") {
		t.Errorf("unexpected error: %v", err)
	}
}

